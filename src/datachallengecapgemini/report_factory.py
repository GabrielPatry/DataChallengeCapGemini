class ReportFactory:
    """Generates the prose sections of an incident report with LLM agents.

    Mirrors :class:`~datachallengecapgemini.plot_factory.PlotFactory`: the
    clusterised incidents dataframe is the main attribute (``df``), completed
    by the asset ``label``. The chat model (Azure OpenAI, gpt-4.1-nano
    deployment) is the ``llm`` attribute, and the context shared by the
    agents (``statistics``, ``clusters``, ``cluster_table``) is precomputed
    at construction.

    Each agent is a small langgraph ``StateGraph`` compiled into a Runnable
    (a ``CompiledGraph``):

    - private ``_*_agent`` methods build and return the compiled graph, so
      intermediate agents can be reused or tested on their own;
    - public ``write_*`` methods invoke the graph and return the generated
      text.

    The token usage of every LLM call is accumulated in ``token_usage`` and
    printed with :meth:`print_token_usage`.
    """

    # Environment variables required to build the default Azure OpenAI LLM
    AZURE_ENV_VARS: ClassVar[tuple[str, ...]] = (
        "AZURE_OPENAI_API_KEY",
        "AZURE_OPENAI_ENDPOINT",
        "AZURE_OPENAI_API_VERSION",
        "AZURE_OPENAI_CHAT_DEPLOYMENT",
    )

    # Maximum number of clusters rendered in the shared cluster summary
    N_SUMMARISED_CLUSTERS: ClassVar[int] = 10

    def __init__(
        self, df: pd.DataFrame, label: str, llm: BaseChatModel | None = None
    ) -> None:
        self.df = df
        self.label = label
        self.token_usage = TokenUsageCallback()
        self.llm = llm if llm is not None else self._default_llm()
        # Context elements shared by every agent
        self.statistics = self._render_statistics()
        self.cluster_table = self._compute_cluster_table()
        self.clusters = self._render_clusters()

    @classmethod
    def _default_llm(cls) -> BaseChatModel:
        """Build the default LLM: Azure OpenAI, gpt-4.1-nano chat deployment."""
        load_dotenv()
        missing = [name for name in cls.AZURE_ENV_VARS if not os.environ.get(name)]
        if missing:
            raise RuntimeError(
                f"Missing Azure OpenAI environment variable(s): "
                f"{', '.join(missing)}. Set them in your environment or in "
                "the .env file at the project root."
            )
        return AzureChatOpenAI(
            azure_deployment=os.environ["AZURE_OPENAI_CHAT_DEPLOYMENT"],
            azure_endpoint=os.environ["AZURE_OPENAI_ENDPOINT"],
            api_key=os.environ["AZURE_OPENAI_API_KEY"],
            api_version=os.environ["AZURE_OPENAI_API_VERSION"],
            temperature=0.2,
        )

    # ------------------------------------------------------------------
    # Context rendering — shared by every agent
    # ------------------------------------------------------------------

    def _render_statistics(self) -> str:
        """Render the key fleet statistics as a text block for the agents."""
        df = self.df
        dates = pd.to_datetime(df["date"])
        severity_counts = df["severity"].value_counts()
        total_cost = df["estimated_cost_eur"].sum()
        total_downtime = df["downtime_hours"].sum()
        top_site = df.groupby("site")["estimated_cost_eur"].sum().idxmax()
        top_equipment = df.groupby("equipment_id")["estimated_cost_eur"].sum().idxmax()
        severity_breakdown = ", ".join(
            f"{level}: {int(severity_counts.get(level, 0))}"
            for level in SEVERITY_LEVELS
        )
        lines = [
            f"- Incidents analysed: {len(df)}",
            f"- Sites covered: {df['site'].nunique()}",
            f"- Equipment monitored: {df['equipment_id'].nunique()}",
            (
                f"- Period: {dates.min().date().isoformat()} "
                f"to {dates.max().date().isoformat()}"
            ),
            f"- Total estimated cost: {total_cost:,.2f} EUR",
            f"- Total downtime: {total_downtime:,.1f} h",
            f"- Average cost per incident: {total_cost / len(df):,.2f} EUR",
            f"- Severity breakdown: {severity_breakdown}",
            f"- Most costly site: {top_site}",
            f"- Most costly equipment: {top_equipment}",
        ]
        return "\n".join(lines)

    def _compute_cluster_table(self) -> pd.DataFrame:
        """Per-cluster aggregates (count, cost, downtime), largest first."""
        return (
            self.df.groupby(["cluster_code", "cluster_name"])
            .agg(
                incident_count=("estimated_cost_eur", "size"),
                total_cost_eur=("estimated_cost_eur", "sum"),
                total_downtime_hours=("downtime_hours", "sum"),
            )
            .reset_index()
            .sort_values("incident_count", ascending=False)
            .reset_index(drop=True)
        )

    def _render_clusters(self) -> str:
        """Render the top thematic clusters as a text block for the agents."""
        n_incidents = len(self.df)
        table = self.cluster_table
        thematic = table[table["cluster_code"] != NOISE_CLUSTER_CODE]
        noise = table[table["cluster_code"] == NOISE_CLUSTER_CODE]

        lines = []
        for _, cluster in thematic.head(self.N_SUMMARISED_CLUSTERS).iterrows():
            cluster_df = self.df[self.df["cluster_code"] == cluster["cluster_code"]]
            top_site = cluster_df.groupby("site")["estimated_cost_eur"].sum().idxmax()
            dominant_severity = cluster_df["severity"].value_counts().idxmax()
            lines.append(
                f"- {cluster['cluster_code']} — {cluster['cluster_name']}: "
                f"{int(cluster['incident_count'])} incidents "
                f"({100 * cluster['incident_count'] / n_incidents:.1f}%), "
                f"{cluster['total_cost_eur']:,.2f} EUR, "
                f"{cluster['total_downtime_hours']:,.1f} h downtime, "
                f"most affected site: {top_site}, "
                f"dominant severity: {dominant_severity}"
            )
        if not noise.empty:
            count = int(noise.iloc[0]["incident_count"])
            lines.append(
                f"- Unclassified (noise) incidents: {count} "
                f"({100 * count / n_incidents:.1f}%)"
            )
        return "\n".join(lines)

    def _base_state(self) -> ReportState:
        """Initial state shared by every agent: label + rendered context."""
        return {
            "label": self.label,
            "statistics": self.statistics,
            "clusters": self.clusters,
        }

    def _run(self, agent: Runnable, state: ReportState) -> ReportState:
        """Invoke *agent* on *state*, tracking the token usage."""
        return agent.invoke(state, config={"callbacks": [self.token_usage]})

    # ------------------------------------------------------------------
    # Agents — each private method compiles a langgraph graph (Runnable)
    # ------------------------------------------------------------------

    def _synopsis_agent(self) -> Runnable:
        """Compiled graph writing the executive synopsis of the report."""
        chain = (
            ChatPromptTemplate.from_messages(
                [
                    ("system", SYNOPSIS_SYSTEM_PROMPT),
                    (
                        "human",
                        (
                            "Asset type: {label}\n\n"
                            "Key statistics:\n{statistics}\n\n"
                            "Cluster summary:\n{clusters}\n\n"
                            "Write the synopsis of the report."
                        ),
                    ),
                ]
            )
            | self.llm
            | StrOutputParser()
        )

        def write_synopsis(state: ReportState) -> ReportState:
            return {"synopsis": chain.invoke(dict(state))}

        graph = _new_state_graph()
        graph.add_node("write_synopsis", write_synopsis)
        graph.add_edge(START, "write_synopsis")
        graph.add_edge("write_synopsis", END)
        return graph.compile()

    def _methodology_agent(self) -> Runnable:
        """Compiled graph writing the methodology section of the report."""
        chain = (
            ChatPromptTemplate.from_messages(
                [
                    ("system", METHODOLOGY_SYSTEM_PROMPT),
                    (
                        "human",
                        (
                            "Asset type: {label}\n\n"
                            "Key statistics:\n{statistics}\n\n"
                            "Write the methodology section of the report."
                        ),
                    ),
                ]
            )
            | self.llm
            | StrOutputParser()
        )

        def write_methodology(state: ReportState) -> ReportState:
            return {"methodology": chain.invoke(dict(state))}

        graph = _new_state_graph()
        graph.add_node("write_methodology", write_methodology)
        graph.add_edge(START, "write_methodology")
        graph.add_edge("write_methodology", END)
        return graph.compile()

    def _cluster_description_agent(self) -> Runnable:
        """Compiled graph writing the description of a single cluster."""
        chain = (
            ChatPromptTemplate.from_messages(
                [
                    ("system", CLUSTER_DESCRIPTION_SYSTEM_PROMPT),
                    (
                        "human",
                        (
                            "Asset type: {label}\n\n"
                            "Cluster: {cluster_name} ({cluster_code})\n\n"
                            "Cluster statistics:\n{cluster_stats}\n\n"
                            "Write the description of this cluster."
                        ),
                    ),
                ]
            )
            | self.llm
            | StrOutputParser()
        )

        def write_cluster_description(state: ReportState) -> ReportState:
            return {"cluster_description": chain.invoke(dict(state))}

        graph = _new_state_graph()
        graph.add_node("write_cluster_description", write_cluster_description)
        graph.add_edge(START, "write_cluster_description")
        graph.add_edge("write_cluster_description", END)
        return graph.compile()

    def _recommendations_agent(self) -> Runnable:
        """Compiled graph writing the recommendations section.

        Recommendations are more complex than the other sections, so this
        agent merges three specialised runnables into a single graph:

        1. ``identify_drivers`` — extract the main cost/downtime drivers;
        2. ``draft_recommendations`` — draft one recommendation per driver;
        3. ``prioritise`` — merge, prioritise and format the final list.
        """
        drivers_chain = (
            ChatPromptTemplate.from_messages(
                [
                    ("system", COST_DRIVERS_SYSTEM_PROMPT),
                    (
                        "human",
                        (
                            "Asset type: {label}\n\n"
                            "Key statistics:\n{statistics}\n\n"
                            "Cluster summary:\n{clusters}\n\n"
                            "List the main cost/downtime drivers."
                        ),
                    ),
                ]
            )
            | self.llm
            | StrOutputParser()
        )
        draft_chain = (
            ChatPromptTemplate.from_messages(
                [
                    ("system", DRAFT_RECOMMENDATIONS_SYSTEM_PROMPT),
                    (
                        "human",
                        (
                            "Asset type: {label}\n\n"
                            "Cost/downtime drivers:\n{cost_drivers}\n\n"
                            "Cluster summary:\n{clusters}\n\n"
                            "Draft one recommendation per driver."
                        ),
                    ),
                ]
            )
            | self.llm
            | StrOutputParser()
        )
        prioritise_chain = (
            ChatPromptTemplate.from_messages(
                [
                    ("system", PRIORITISE_RECOMMENDATIONS_SYSTEM_PROMPT),
                    (
                        "human",
                        (
                            "Asset type: {label}\n\n"
                            "Key statistics:\n{statistics}\n\n"
                            "Draft recommendations:\n{draft_recommendations}\n\n"
                            "Write the final prioritised bullet list."
                        ),
                    ),
                ]
            )
            | self.llm
            | StrOutputParser()
        )

        def identify_drivers(state: ReportState) -> ReportState:
            return {"cost_drivers": drivers_chain.invoke(dict(state))}

        def draft_recommendations(state: ReportState) -> ReportState:
            return {"draft_recommendations": draft_chain.invoke(dict(state))}

        def prioritise(state: ReportState) -> ReportState:
            return {"recommendations": prioritise_chain.invoke(dict(state))}

        graph = _new_state_graph()
        graph.add_node("identify_drivers", identify_drivers)
        graph.add_node("draft_recommendations", draft_recommendations)
        graph.add_node("prioritise", prioritise)
        graph.add_edge(START, "identify_drivers")
        graph.add_edge("identify_drivers", "draft_recommendations")
        graph.add_edge("draft_recommendations", "prioritise")
        graph.add_edge("prioritise", END)
        return graph.compile()

    def _conclusion_agent(self) -> Runnable:
        """Compiled graph writing the conclusion of the report."""
        chain = (
            ChatPromptTemplate.from_messages(
                [
                    ("system", CONCLUSION_SYSTEM_PROMPT),
                    (
                        "human",
                        (
                            "Asset type: {label}\n\n"
                            "Key statistics:\n{statistics}\n\n"
                            "Synopsis:\n{synopsis}\n\n"
                            "Recommendations:\n{recommendations}\n\n"
                            "Write the conclusion of the report."
                        ),
                    ),
                ]
            )
            | self.llm
            | StrOutputParser()
        )

        def write_conclusion(state: ReportState) -> ReportState:
            return {"conclusion": chain.invoke(dict(state))}

        graph = _new_state_graph()
        graph.add_node("write_conclusion", write_conclusion)
        graph.add_edge(START, "write_conclusion")
        graph.add_edge("write_conclusion", END)
        return graph.compile()

    # ------------------------------------------------------------------
    # Public API — each method invokes an agent and returns generated text
    # ------------------------------------------------------------------

    def write_synopsis(self) -> str:
        """Generate the executive synopsis of the report."""
        return self._run(self._synopsis_agent(), self._base_state())["synopsis"]

    def write_methodology(self) -> str:
        """Generate the methodology section of the report."""
        return self._run(self._methodology_agent(), self._base_state())["methodology"]

    def write_cluster_description(
        self, cluster_code: str, cluster_name: str, cluster_stats: str
    ) -> str:
        """Generate the description of a single cluster."""
        state = self._base_state()
        state["cluster_code"] = cluster_code
        state["cluster_name"] = cluster_name
        state["cluster_stats"] = cluster_stats
        return self._run(self._cluster_description_agent(), state)[
            "cluster_description"
        ]

    def write_cluster_descriptions(
        self, n_clusters: int = N_DETAILED_CLUSTERS
    ) -> list[str]:
        """Generate one description per top thematic cluster (largest first)."""
        n_incidents = len(self.df)
        thematic = self.cluster_table[
            self.cluster_table["cluster_code"] != NOISE_CLUSTER_CODE
        ]
        descriptions = []
        for _, cluster in thematic.head(n_clusters).iterrows():
            code = cluster["cluster_code"]
            cluster_df = self.df[self.df["cluster_code"] == code]
            top_site = cluster_df.groupby("site")["estimated_cost_eur"].sum().idxmax()
            dominant_severity = cluster_df["severity"].value_counts().idxmax()
            cluster_stats = (
                f"{int(cluster['incident_count'])} incidents "
                f"({100 * cluster['incident_count'] / n_incidents:.1f}% of all "
                f"incidents), {cluster['total_cost_eur']:,.2f} EUR total "
                f"estimated cost, "
                f"{cluster['total_downtime_hours']:,.1f} h total downtime, "
                f"most affected site: {top_site}, "
                f"dominant severity: {dominant_severity}"
            )
            descriptions.append(
                self.write_cluster_description(
                    code, cluster["cluster_name"], cluster_stats
                )
            )
        return descriptions

    def write_recommendations(self) -> str:
        """Generate the recommendations section (multi-agent graph)."""
        return self._run(self._recommendations_agent(), self._base_state())[
            "recommendations"
        ]

    def write_conclusion(self, synopsis: str, recommendations: str) -> str:
        """Generate the conclusion, given the synopsis and recommendations."""
        state = self._base_state()
        state["synopsis"] = synopsis
        state["recommendations"] = recommendations
        return self._run(self._conclusion_agent(), state)["conclusion"]

    def generate_prose(
        self, n_clusters: int = N_DETAILED_CLUSTERS
    ) -> dict[str, str | list[str]]:
        """Generate every prose block needed by the report templates."""
        print(f"[{self.label}] Generating report prose with LLM agents...")
        synopsis = self.write_synopsis()
        recommendations = self.write_recommendations()
        return {
            "synopsis": synopsis,
            "methodology": self.write_methodology(),
            "cluster_descriptions": self.write_cluster_descriptions(n_clusters),
            "recommendations": recommendations,
            "conclusion": self.write_conclusion(synopsis, recommendations),
        }

    def print_token_usage(self) -> None:
        """Print the token usage accumulated by this factory's agents."""
        print(f"Token usage ({self.label}): {self.token_usage.summary()}")


